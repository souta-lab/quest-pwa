export function normalizeRecall(input: string) {
  return input
    .normalize("NFKC")
    .trim()
    .toLowerCase()
    .replace(/[−‐–—]/g, "-")
    .replace(/[，、]/g, ",")
    .replace(/[\s$。．]/g, "");
}
export function checkRecall(check: Check, input: string) {
  const value = normalizeRecall(input);
  return !!value && check.answers.some((a) => normalizeRecall(a) === value);
}
