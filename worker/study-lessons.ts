export function foundationLesson(
  q: Pick<Question, "subject" | "topic" | "stem"> & {
    generation?: Question["generation"];
  },
) {
  const item = lessonsFor(q).find((l) => examples[l.title]) ?? lessonsFor(q)[0];
  return foundationFromLesson(item);
}
export function foundationFromLesson(item: Lesson) {
  const example = examples[item.title];
  return {
    title: item.title,
    knowledge: item.knowledge,
    method: item.start,
    example: example
      ? { problem: example[0], steps: example[1], conclusion: example[2] }
      : null,
    recall:
      "例を閉じて、使った知識と最初の操作を自分の言葉で思い出そう。次は問題で試してみよう。",
    source: "運営作成の基礎教材",
  };
}
