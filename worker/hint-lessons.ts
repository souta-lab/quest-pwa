export function lessonsFor(
  q: Pick<Question, "subject" | "topic" | "stem"> & {
    generation?: Question["generation"];
  },
): Lesson[] {
  const topic = aliases[q.topic] ?? q.topic;
  const pool = unitLessons[topic] ??
    (q.subject.startsWith("math") ? math[topic] : undefined) ??
    science[topic] ??
    subjects[q.subject] ?? [
      lesson(
        "情報を整理する",
        "条件は使ってよい前提、結論は示したいこと。定義は用語の意味を定めるもの。条件と結論は別の役割を持つ。",
        "問題文を条件と求めるものに分けて書く。",
      ),
    ];
  return pool
    .map((item, index) => ({
      item,
      index,
      score:
        (item.match?.test(q.stem) ? 1 : 0) +
        (q.stem.includes(item.title) ? 2 : 0) +
        (q.generation?.focus?.includes(item.title) ? 4 : 0),
    }))
    .sort((a, b) => b.score - a.score || a.index - b.index)
    .map((x) => x.item);
}
export function renderLesson(item: Lesson) {
  return `${item.title}\n\n知っておくこと\n${item.knowledge}\n\n最初の一歩\n${item.start}`;
}
