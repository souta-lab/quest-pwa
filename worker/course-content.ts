export type CourseLesson = ReturnType<typeof foundationFromLesson> & {
  prompt: string;
};
const overrides: Record<string, CourseLesson[]> = {};
function add(
  subject: string,
  topic: string,
  title: string,
  knowledge: string,
  method: string,
  problem: string,
  steps: string[],
  conclusion: string,
  prompt: string,
  answers: string[],
  explanation: string,
) {
  recallChecks[title] = { prompt, answers, explanation };
  const item = {
    title,
    knowledge,
    method,
    example: { problem, steps, conclusion },
    recall: "教材を閉じて、下の短い問いに自分の答えを書いてみよう。",
    source: "運営作成の基礎教材",
    prompt,
  };
  (overrides[`${subject}/${topic}`] ??= []).push(item);
}
