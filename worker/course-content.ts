export function courseLessons(subject: string, topic: string): CourseLesson[] {
  const key = `${subject}/${topic}`;
  if (overrides[key]) return overrides[key];
  const filter = chosen[key];
  const pool: Lesson[] = lessonsFor({ subject, topic, stem: "" });
  return pool
    .filter(
      (l) => (!filter || filter.includes(l.title)) && recallChecks[l.title],
    )
    .map((l) => ({
      ...foundationFromLesson(l),
      prompt: recallChecks[l.title].prompt,
    }));
}
